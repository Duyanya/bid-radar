    if not ok_prov:
        return False, "排除", why_prov

    # 第 1 步：机房/机电/土建类（标题强命中即排除，优先于任何相关性）
    mr = _is_machine_room(title)
    if mr:
        return False, "排除", f"机房工程:{mr[:3]}"

    # 第 1.5 步：设备/物料采购（买设备不是建网）
    eq = _is_equipment_purchase(title)
    if eq:
        return False, "排除", f"设备采购:{eq[:3]}"

    # 第 1.6 步：实体沙盘/展厅模型（物理模型，不是网络系统）
    if "沙盘" in title:
        phys = [w for w in ("实体模型", "模型制作", "展厅", "制作", "安装调试", "沙具") if w in title]
        if phys or re.search(r"\d+\s*套", title):
            return False, "排除", "实体沙盘模型"

    # 第 1.7 步：直辖市「XX局」= 区局（分公司级，非省公司）
    if re.search(r"(?:上海|北京|天津|重庆)(?:市)?(?:公司|电信|移动|联通)?[\u4e00-\u9fa5]{2,3}局(?!长)", title) \
            and "传输局" not in title:
        return False, "排除", "区局"

    # 第 2 步：其他排除项（只匹配标题）
    direct = [u for u in DIRECT_UNITS if u in title]
    probe = title
    for u in direct:
        probe = probe.replace(u, "")   # 省直属单位名不算「子公司」
    for cat, kws in EXCLUDE:
        if cat == "机房":
            continue
        hit = [k for k in kws if k in probe]
        if not hit:
            continue
        if cat == "维保项目" and any(w in title for w in BUILD_SIGNAL):
            continue    # 「运维平台研发/系统建设」属建设类，不算存量维护
        return False, "排除", f"{cat}:{hit[:3]}"

    # 第 2 步：强相关（标题+正文都看，提高召回）
    # 注意：英文缩写需词边界匹配，否则 AIDC 会被 IDC 命中、SDN 会被误配
    text = f"{title} {content}"
    strong_hits = []
    for k in STRONG:
        if re.fullmatch(r"[A-Za-z0-9\-]+", k):
            if re.search(r"(?<![A-Za-z])" + re.escape(k) + r"(?![A-Za-z])", text):
                strong_hits.append(k)
        elif k in text:
            strong_hits.append(k)
    if strong_hits:
        return True, "强相关", ",".join(strong_hits[:3])

    # 第 3 步：弱相关
    weak_hits = [k for k in WEAK if k in text]
    if weak_hits:
        return True, "弱相关", ",".join(weak_hits[:3])

    # 第 4 步：省公司/集团总部 + 研发建设信号 → 研发类项目
    # 有些公告标题只写「XX研发项目」，不带网/云/平台等网络域词（如「AI赋能生产研发」），
    # 但需求口径本来就包含研发项目，不能因为缺网络域词就丢掉。
    # 前提：主体已通过省级校验，且机房/设备/维保等排除项都已在前面的步骤拦住。
    research_hits = [k for k in RESEARCH_KEEP if k in title]
    if research_hits:
        return True, "研发类", ",".join(research_hits[:3])

    return False, "无关", "无网络域关键词"


