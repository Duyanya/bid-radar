QTY_RE = re.compile(r"\d{2,6}\s*(台|套|块|面|架|只|件|个)")


def _is_equipment_purchase(title):
    """设备/物料采购识别（用户 2026-11-12：设备采购必须彻底剔除）。

    规则：命中【硬件名词】+【采购动词】且没有研发/开发/研究/集成等建设信号 → 剔除。
    例：智能家庭网关集中采购、混合光缆公开招标采购、室外铝合金光纤槽道采购、
        5G精细化分流设备建设工程采购、边缘计算单元（MEC）…249台 → 全部剔除。
    反例（必须保留）：定制软件开发服务采购项目、网络集成服务采购项目。
    """
    if not title:
        return None
    hw = [w for w in HW_WORDS if w in title]
    qty = QTY_RE.search(title)
    if not hw and not qty:
        return None
    if not any(b in title for b in BUY_WORDS):
        return None
    # 建设信号：研发/开发/研究/集成/设计/定制/优化/验证 等，说明买的是服务或研发成果
    if any(d in title for d in DEV_WORDS):
        return None
    return f"设备采购:{(hw[:2] or [qty.group(0)])[0]}"


